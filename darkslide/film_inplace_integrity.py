REFERENCE = Path(__file__).with_name('film_inplace_reference.json')
REFERENCE_SHA256 = 'a822d6ce54c31e36b77fd32fb9bd09fb2753a744023f5187d8923a966ad5befd'
CANDIDATE_SHA256 = '9eb72ac69ddb302a56b87256820cf27f0aad049a97da69068111cdc7a6a624e5'
# GR III 2.20: captured by tools/capture_v29_reference_220.py after the 2.10 equivalence check.
REFERENCE_220 = Path(__file__).with_name('film_inplace_reference_220.json')
REFERENCE_220_SHA256 = '283a13d17b9fbd5119389eb6a3318f6da8d351daae4df900ea6e59b23b9ebdd9'

def reference_file():
    return (REFERENCE_220, REFERENCE_220_SHA256) if fwaddr.is_220() else (REFERENCE, REFERENCE_SHA256)

def data_addresses(selection):
    if not selection:return set()
    spans=[(fa(data.BASE)+416,64),(fa(data.BASE)+1272,96)]
    for slot in selection:
        i=slot-8
        spans.extend(((fa(data.BASE)+84*i,84),(fa(data.BASE)+336+20*i,18),(fa(data.BASE)+480+198*i,198)))
        spans.extend((fa(0x55018d94)+4*a,4) for a in data.ALIASES[slot])
    return {a for start,n in spans for a in range(start,start+n)}

def fingerprint(overlay, dynamic):
    shared=sorted(set(overlay)-dynamic)
    h=hashlib.sha256()
    for at in shared:h.update(struct.pack('<IB',at,overlay[at]))
    coverage=hashlib.sha256(b''.join(struct.pack('<I',a) for a in sorted(overlay))).hexdigest()
    return dict(shared_sha256=h.hexdigest(),shared_bytes=len(shared),coverage_sha256=coverage,total_bytes=len(overlay))

def verify(raw, windows, selection, profiles, *, layout):
    """Check exact declared byte coverage and fixed shared bytes, not ARM safety.

    The reference was captured once from a frozen candidate and reviewed; it is
    not regenerated by calling the writer during verification.
    """
    if layout in ('inplace_history_cache_exit_vivid5_v1', 'inplace_history_cache_exit_vivid5_220_v1'):
        from . import film_vivid_fifth_readback
        return film_vivid_fifth_readback.verify(raw,windows,selection,profiles,layout=layout)
    result=data.verify(raw,windows,selection,profiles,layout=layout)
    overlay={w.address+i:b for w in windows for i,b in enumerate(w.replacement)}
    dynamic=data_addresses(selection)
    data.need(dynamic<=set(overlay),'missing data coverage')
    try:
        path,digest=reference_file()
        reference_bytes=path.read_bytes()
        data.need(hashlib.sha256(reference_bytes).hexdigest()==digest,'reference digest')
        reference=json.loads(reference_bytes)
        data.need(type(reference['schema']) is int and reference['schema']==1 and
                  reference['candidate_source_sha256']==CANDIDATE_SHA256,'reference version')
    except (OSError,ValueError,KeyError,TypeError) as exc:
        raise data.ReadbackError('invalid or missing reference') from exc
    data.need(reference['layout']==layout and reference['original_sha256']==fwaddr.payload_sha(data.ORIGINAL_SHA),'reference identity')
    mask=sum(1<<(s-8) for s in selection)
    data.need(fingerprint(overlay,dynamic)==reference['masks'][str(mask)],'shared bytes or complete coverage mismatch')
    return dict(result,shared_bytes_match_reference=True,complete_window_coverage_verified=True,
                shared_code_verified=False,production_approved=False)

def verify_project(raw, windows, changes, profiles, *, planned_layout, checked_layout):
    """Read-only App adapter. Complete project state required; no writer calls."""
    if planned_layout in ('inplace_history_cache_exit_vivid5_v1', 'inplace_history_cache_exit_vivid5_220_v1') or checked_layout in ('inplace_history_cache_exit_vivid5_v1', 'inplace_history_cache_exit_vivid5_220_v1'):
        from . import film_vivid_fifth_readback
        return film_vivid_fifth_readback.verify_project(raw,windows,changes,profiles,planned_layout=planned_layout,checked_layout=checked_layout)
    data.need(planned_layout==checked_layout==data.LAYOUT,'App layout mismatch')
    data.need(type(changes) is dict,'project changes')
    selection={}
    for key,value in changes.items():
        if type(value) is dict and 'film' in value:
            data.need(type(key) is str and key in ('8','9','10','11'),'project film slot')
            data.need(type(value['film']) is str and bool(value['film']),'project film identity')
            selection[int(key)]=value['film']
    return verify(raw,windows,selection,profiles,layout=checked_layout)
