#!/usr/bin/env python3
"""Build only ARM code fragments. Never reads or generates a firmware image.

Run from a source checkout with LLVM clang available. --check reconstructs into
memory and compares byte-for-byte without replacing shipped resources.
"""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import sys

APP = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(APP))
from darkslide import film_inplace_cache, gr3x_inplace, film_vivid_fifth
from darkslide.arm_compiler import resolve_clang
from darkslide.film_arm_assemble import assemble
from darkslide.film_precompiled import source_key


def build(vivid_five=False):
    families = {}
    for family, module in [('GRIII-2.10-v29', film_inplace_cache), ('GRIIIx-1.60-v29', gr3x_inplace)]:
        family_key = ('GRIII-2.10' if module is film_inplace_cache else 'GRIIIx-1.60')
        if vivid_five:family = film_vivid_fifth.FAMILIES[family_key]
        entries = {}; combinations = {}
        for mask in (range(16,32) if vivid_five else range(1,16)):
            calls = []
            def compile_one(source, base):
                blob = assemble(source, base)
                key = source_key(source, base)
                row = dict(size=len(blob), sha256=hashlib.sha256(blob).hexdigest(), hex=blob.hex())
                if key in entries and entries[key] != row:
                    raise ValueError('non-deterministic assembly')
                entries[key] = row; calls.append(key)
                return blob
            addresses, code = (film_vivid_fifth.build_code(mask, family_key, compile_one) if vivid_five
                               else module.build_code(mask, compile_one))
            combinations[str(mask)] = dict(calls=calls, addresses=addresses,
                final_sizes={role: len(blob) for role,blob in code.items()})
        families[family] = dict(layout=film_vivid_fifth.LAYOUTS[family_key] if vivid_five else module.LAYOUT, official_payload_sha256=module.SHA,
                               entries=entries, combinations=combinations)
    # Record transitive source producers, including the assembler, in the artifact.
    names = ['film_inplace_cache.py','gr3x_inplace.py','film_arm_assemble.py',
             'film_scheme_c.py','gr3x_inplace_support.py','_vendor/gr3_four_curve_hooks.py',
             '_vendor/gr3_film_hooks.py']
    if vivid_five:names += ['film_vivid_fifth.py','film_slots.py']
    sources = {name:hashlib.sha256((APP/'darkslide'/name).read_bytes()).hexdigest()
               for name in names }
    version = subprocess.run([resolve_clang(),'--version'],capture_output=True,text=True,check=True).stdout.splitlines()[0]
    return dict(schema=1, compiler=version, target='armv7a-none-eabi', sources=sources,
                provenance='Distributed Darkslide sources; MIT-derived hooks retain app/darkslide/_vendor notices; no original firmware bytes.',
                families=families)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    parser.add_argument('--vivid-five',action='store_true',help='build the separate Vivid fifth-slot resource')
    args=parser.parse_args()
    built=build(args.vivid_five)
    raw=(json.dumps(built,sort_keys=True,indent=2)+'\n').encode()
    path=APP/('darkslide/data/film_arm_vivid5_v1.json' if args.vivid_five else 'darkslide/data/film_arm_v1.json')
    pin=APP/('darkslide/film_precompiled_vivid5_pin.py' if args.vivid_five else 'darkslide/film_precompiled_pin.py')
    digest=hashlib.sha256(raw).hexdigest()
    variable='VIVID_BUNDLE_SHA256' if args.vivid_five else 'BUNDLE_SHA256'
    suffix=' --vivid-five' if args.vivid_five else ''
    pin_raw=("# Generated by tools/build_film_arm_bundle.py%s; reviewed with the source bundle.\n%s = %r\n" % (suffix,variable,digest)).encode()
    historical=False
    if args.check:
        # Released resources are immutable. Reconstruct every entry, layout,
        # source/base key and combination, while retaining historical file-hash
        # metadata after version dispatch is added to the same source module.
        from darkslide.film_precompiled_pin import BUNDLE_SHA256
        from darkslide.film_precompiled_vivid5_pin import VIVID_BUNDLE_SHA256
        shipped_raw=path.read_bytes()
        pinned=VIVID_BUNDLE_SHA256 if args.vivid_five else BUNDLE_SHA256
        if hashlib.sha256(shipped_raw).hexdigest()!=pinned:raise SystemExit('released bundle pin differs')
        shipped=json.loads(shipped_raw)
        for key in ('schema','target','families'):
            if shipped[key]!=built[key]:raise SystemExit('released ARM reconstruction differs: '+key)
        historical=shipped['sources']!=built['sources']
        digest=hashlib.sha256(shipped_raw).hexdigest()
    else:
        if path.exists():
            raise SystemExit('released resource is frozen; use --check')
        path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(raw);pin.write_bytes(pin_raw)
    print(json.dumps(dict(sha256=digest,size=path.stat().st_size,checked=args.check,
                         vivid_five=args.vivid_five,historical_source_metadata=historical)))

if __name__=='__main__':main()
