#!/usr/bin/env python3
"""Build the GR III 2.20 / IIIx 1.70 ARM fragment bundle. Never reads a firmware image.

Same sources as tools/build_film_arm_bundle.py, assembled at the relocated addresses
(fwaddr, data/reloc_220.json). Written to darkslide/data/film_arm_220_v1.json with its
own pin, so the 2.10 / 1.60 bundle stays byte-identical. --check compares only.
"""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import sys

APP = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(APP))
from darkslide import film_inplace_cache, gr3x_inplace, film_vivid_fifth, fwaddr, models  # noqa: E402
from darkslide.arm_compiler import resolve_clang  # noqa: E402
from darkslide.film_arm_assemble import assemble  # noqa: E402
from darkslide.film_precompiled import source_key  # noqa: E402


def build(vivid_five=False):
    families = {}
    for family, module, model in [('GRIII-2.20-v29', film_inplace_cache, models.GR3_220),
                                  ('GRIIIx-1.70-v29', gr3x_inplace, models.GR3X_170)]:
        base_family=family.removesuffix('-v29')
        if vivid_five:family=film_vivid_fifth.FAMILIES[base_family]
        entries = {}; combinations = {}
        with fwaddr.firmware(model):
            for mask in (range(16,32) if vivid_five else range(1,16)):
                calls = []
                def compile_one(source, base):
                    blob = assemble(source, base)
                    key = source_key(source, base)
                    row = dict(size=len(blob), sha256=hashlib.sha256(blob).hexdigest(), hex=blob.hex())
                    if key in entries and entries[key] != row:
                        raise ValueError('non-deterministic assembly')
                    entries[key] = row; calls.append(key)
                    return blob
                addresses, code = (film_vivid_fifth.build_code(mask,base_family,compile_one) if vivid_five
                                   else module.build_code(mask, compile_one))
                combinations[str(mask)] = dict(calls=calls, addresses=addresses,
                    final_sizes={role: len(blob) for role, blob in code.items()})
        families[family] = dict(layout=film_vivid_fifth.LAYOUTS[base_family] if vivid_five else module.LAYOUT, official_payload_sha256=model.payload_sha,
                               entries=entries, combinations=combinations)
    names = ['film_inplace_cache.py', 'gr3x_inplace.py', 'film_arm_assemble.py',
             'film_scheme_c.py', 'gr3x_inplace_support.py', '_vendor/gr3_four_curve_hooks.py',
             '_vendor/gr3_film_hooks.py', 'fwaddr.py', 'data/reloc_220.json']
    if vivid_five:names+=['film_vivid_fifth.py','film_slots.py']
    sources = {name: hashlib.sha256((APP / 'darkslide' / name).read_bytes()).hexdigest() for name in names}
    version = subprocess.run([resolve_clang(), '--version'], capture_output=True, text=True, check=True).stdout.splitlines()[0]
    return dict(schema=1, compiler=version, target='armv7a-none-eabi', sources=sources,
                provenance='Distributed Darkslide sources at GR III 2.20 / IIIx 1.70 addresses; MIT-derived hooks retain app/darkslide/_vendor notices; no original firmware bytes.',
                families=families)


def main():
    parser = argparse.ArgumentParser(description=__doc__); parser.add_argument('--check', action='store_true')
    parser.add_argument('--vivid-five',action='store_true',help='build the separate 2.20 / 1.70 fifth-slot resource')
    args = parser.parse_args();built=build(args.vivid_five)
    raw = (json.dumps(built, sort_keys=True, indent=2) + '\n').encode()
    path = APP / ('darkslide/data/film_arm_vivid5_220_v1.json' if args.vivid_five else 'darkslide/data/film_arm_220_v1.json')
    pin = APP / ('darkslide/film_precompiled_vivid5_pin_220.py' if args.vivid_five else 'darkslide/film_precompiled_pin_220.py')
    digest = hashlib.sha256(raw).hexdigest()
    variable='VIVID_BUNDLE_220_SHA256' if args.vivid_five else 'BUNDLE_220_SHA256'
    suffix=' --vivid-five' if args.vivid_five else ''
    pin_raw = ("# Generated by tools/build_film_arm_bundle_220.py%s; reviewed with the source bundle.\n%s = %r\n" % (suffix,variable,digest)).encode()
    historical=False
    if args.check:
        if args.vivid_five:
            if path.read_bytes()!=raw or pin.read_bytes()!=pin_raw:raise SystemExit('new five-slot bundle differs; inspect sources/compiler version')
        else:
            from darkslide.film_precompiled_pin_220 import BUNDLE_220_SHA256
            shipped_raw=path.read_bytes()
            if hashlib.sha256(shipped_raw).hexdigest()!=BUNDLE_220_SHA256:raise SystemExit('released 2.20 bundle pin differs')
            shipped=json.loads(shipped_raw)
            for key in ('schema','target','families'):
                if shipped[key]!=built[key]:raise SystemExit('released 2.20 ARM reconstruction differs: '+key)
            historical=shipped['sources']!=built['sources'];digest=hashlib.sha256(shipped_raw).hexdigest()
    else:
        if not args.vivid_five and path.exists():raise SystemExit('released 2.20 resource is frozen; use --check')
        path.write_bytes(raw); pin.write_bytes(pin_raw)
    print(json.dumps(dict(sha256=digest,size=path.stat().st_size,checked=args.check,
                         vivid_five=args.vivid_five,historical_source_metadata=historical)))


if __name__ == '__main__':
    main()
